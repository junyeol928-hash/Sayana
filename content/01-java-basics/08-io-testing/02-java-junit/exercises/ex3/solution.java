public class TicketCases {

    /**
     * チケット料金 price(int age) のテストケースを返す。
     * 各要素は {年齢, 期待する料金}。
     */
    public static int[][] boundaryCases() {
        return new int[][] {
            {-1, -1},     // 負の年齢はエラー
            {0, 0},       // 最小の正常値
            {3, 0},       // 0〜5歳の代表
            {5, 0},       // 境界:無料の最後
            {6, 1000},    // 境界:子ども料金の最初
            {9, 1000},    // 6〜12歳の代表
            {12, 1000},   // 境界:子ども料金の最後
            {13, 1900},   // 境界:一般料金の最初
            {30, 1900},   // 13〜64歳の代表
            {64, 1900},   // 境界:一般料金の最後
            {65, 1300},   // 境界:シニア料金の最初
            {80, 1300},   // 65歳以上の代表
        };
    }

    public static void main(String[] args) {
        for (int[] c : boundaryCases()) {
            System.out.println(c[0] + "歳 → " + c[1] + "円");
        }
    }
}
